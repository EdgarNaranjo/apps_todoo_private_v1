class ProjectTaskBoardSync(models.Model):
    """Sincroniza viewer_ids del board cuando se asignan tareas."""
    _inherit = "project.task"

    def _sync_board_viewers(self):
        """Add to viewer_ids the users assigned to sprint tasks
        que tengan el grupo Board/Viewer o Board/Editor."""
        viewer_group = self.env.ref(
            "todoo_sprint_board_project.group_sprint_board_viewer",
            raise_if_not_found=False,
        )
        if not viewer_group:
            return
        for task in self.filtered(lambda t: t.sprint_id and t.user_ids):
            boards = self.env["sprint.board"].search([
                ("sprint_id", "=", task.sprint_id.id),
                ("state", "=", "open"),
            ])
            if not boards:
                continue
            # Usuarios asignados que tienen el grupo Viewer/Editor
            new_viewers = task.user_ids.filtered(
                lambda u: not u.share and viewer_group in u.groups_id
            )
            if not new_viewers:
                continue
            for board in boards:
                already = board.viewer_ids | board.responsible_ids | board.creator_id
                to_add = new_viewers - already
                if to_add:
                    board.sudo().write({"viewer_ids": [(4, u.id) for u in to_add]})

    def write(self, vals):
        result = super().write(vals)
        if "user_ids" in vals:
            self._sync_board_viewers()
        return result

    @api.model_create_multi
    def create(self, vals_list):
        records = super().create(vals_list)
        records._sync_board_viewers()
        return records
